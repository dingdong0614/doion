// 제작 패키지 비교표: "○○ 전체 포함"을 풀어서 누적 기능표로 만듦
export function buildMatrix() {
  const rows: { feature: string; from: number }[] = [];
  buildPlans.forEach((p, i) => p.features.filter((f) => !f.endsWith("전체 포함")).forEach((feature) => rows.push({ feature, from: i })));
  return rows;
}
